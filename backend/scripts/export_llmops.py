"""Generate docs/llmops_results.md from the database (Phase 11). Nothing in that file is
handwritten: every number is read from llm_calls / pipeline_runs / qa_logs / eval_runs at the
moment this script runs. Re-run it after new traffic or a new eval run.

    cd backend
    python -m scripts.export_llmops                    # all time
    python -m scripts.export_llmops --from 2026-11-07 --to 2026-11-09
    python -m scripts.export_llmops --out ../docs/llmops_results.md
"""

import argparse
from datetime import UTC, date, datetime
from pathlib import Path
from typing import Any

from app.core.config import REPO_ROOT

DEFAULT_OUT = REPO_ROOT / "docs" / "llmops_results.md"


def fmt(v: Any, nd: int = 4) -> str:
    if v is None:
        return "n/a"
    if isinstance(v, bool):
        return "yes" if v else "no"
    if isinstance(v, float):
        if abs(v) >= 100:
            return f"{v:,.1f}"  # latencies, seconds
        return (f"{v:.{nd}f}".rstrip("0").rstrip(".")) or "0"  # rates, scores
    if isinstance(v, int):
        return f"{v:,}"
    if isinstance(v, datetime):
        return v.astimezone(UTC).strftime("%Y-%m-%d %H:%M UTC") if v.tzinfo else v.strftime("%Y-%m-%d %H:%M")
    return str(v).replace("|", "\\|")


def money(v: float | None) -> str:
    return "n/a" if v is None else f"${v:,.6f}"


def table(headers: list[str], rows: list[list[Any]]) -> str:
    if not rows:
        return "_No data._\n"
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    out += ["| " + " | ".join(c if isinstance(c, str) else fmt(c) for c in r) + " |" for r in rows]
    return "\n".join(out) + "\n"


def lat(s: dict[str, Any]) -> list[Any]:
    return [s["n"], s["p50_ms"], s["p95_ms"]]


def build(db, metrics, registry, f, generated_at: datetime) -> str:
    from app.services.evaluation import queries

    s = metrics.summary(f)
    md: list[str] = [
        "# LLMOps results (generated)",
        "",
        f"> **Generated by `python -m scripts.export_llmops` on {fmt(generated_at)}** from the database. "
        "Do not edit by hand; re-run the script. How each metric is defined: [llmops.md](llmops.md).",
        "",
        f"Window: {fmt(f.date_from) if f.date_from else 'all time'} to {fmt(f.date_to) if f.date_to else 'now'} "
        f"(first call {fmt(s['first_call_at'])}, last call {fmt(s['last_call_at'])}). "
        "Live traffic only: evaluation calls (tasks `eval_*`) are excluded from sections 1-6.",
        "",
        "## 1. Overview",
        "",
        table(["Metric", "Value"], [
            ["Model calls", s["calls"]],
            ["Tokens (in / out)", f"{fmt(s['input_tokens'])} / {fmt(s['output_tokens'])}"],
            ["Actual cost (free tier)", money(s["cost_usd"])],
            ["Equivalent cost at listed paid prices", money(s["equivalent_cost_usd"])
             + (f" ({s['unpriced_calls']} calls unpriced)" if s["unpriced_calls"] else "")],
            ["Failed calls / error rate", f"{s['failed_calls']} / {fmt(s['error_rate'])}"],
            ["JSON parse failures / rate", f"{s['json_invalid_calls']} / {fmt(s['parse_failure_rate'])}"],
            ["Transcriptions / pooled real-time factor (M1)", f"{s['transcriptions']} / {fmt(s['rtf_overall'])}"],
            ["Questions (/ask + /chat, ok)", s["questions"]],
            ["Prices file checked", s["pricing_checked"]],
        ]),
    ]

    t = metrics.transcription(f)
    md += ["## 2. M1: transcription time and real-time factor", "",
           "RTF = processing seconds / audio seconds of the `transcribing` stage (below 1 = faster than real time).",
           "",
           table(["Lecture", "Audio (s)", "Processing (s)", "RTF", "Started"],
                 [[r["title"] or str(r["lecture_id"]), r["audio_sec"], r["processing_sec"], r["rtf"], r["started_at"]]
                  for r in t["runs"]]),
           f"Pooled RTF {fmt(t['rtf_overall'])}, median {fmt(t['rtf_median'])} over {t['n']} run(s).", ""]

    md += ["## 3. M2-M3 (and every task): latency of successful requests", "",
           table(["Task", "Provider", "Model", "n", "p50 (ms)", "p95 (ms)"],
                 [[r["task"], r["provider"], r["model"], *lat(r)] for r in metrics.latency_by_task(f)])]

    md += ["## 4. M4: end-to-end question latency per generator (qa_logs)", "",
           table(["Generator", "n", "p50 (ms)", "p95 (ms)", "Answered p50", "Model refusal p50",
                  "Threshold refusal p50", "Retrieval p50"],
                 [[r["generator"], *lat(r), r["answered"]["p50_ms"], r["refused_by_model"]["p50_ms"],
                   r["refused_by_threshold"]["p50_ms"], r["retrieval"]["p50_ms"]] for r in metrics.qa_latency(f)])]

    md += ["## 5. M5: tokens and cost", ""]
    for group, title in (("task", "Per task"), ("day", "Per day (UTC)"), ("lecture", "Per lecture")):
        md += [f"**{title}**", "",
               table([title.split()[1].capitalize(), "Calls", "Tokens in", "Tokens out", "Actual cost",
                      "Equivalent cost", "Unpriced calls"],
                     [[r["label"], r["calls"], r["input_tokens"], r["output_tokens"], money(r["cost_usd"]),
                       money(r["equivalent_cost_usd"]), r["unpriced_calls"]] for r in metrics.usage(f, group)])]

    e = metrics.errors(f)
    md += ["## 6. Errors, JSON parse failures and refusals", "",
           table(["Task", "Requests", "Failed", "Error rate", "Rate limited", "JSON invalid", "Parse-failure rate",
                  "Failed after repair"],
                 [[r["task"], r["requests"], r["failed"], r["error_rate"], r["rate_limited"], r["json_invalid"],
                   r["parse_failure_rate"], r["repair_failed"]] for r in e["by_task"]]),
           "**Refusals by layer** (threshold = below `RAG_MIN_SCORE`, no LLM call; model = `answerable: false`)", "",
           table(["Generator", "Questions", "Answered", "Refused: threshold", "Refused: model", "Errors",
                  "Refusal rate"],
                 [[r["generator"], r["questions"], r["answered"], r["below_threshold"], r["not_in_chunks"],
                   r["errors"], r["refusal_rate"]] for r in metrics.refusals(f)]),
           "**Per prompt version**", "",
           table(["Prompt", "Task", "Requests", "p50 (ms)", "p95 (ms)", "Error rate", "Parse-failure rate",
                  "Mean tokens in / out"],
                 [[r["prompt_version"], r["task"], r["requests"], r["p50_ms"], r["p95_ms"], r["error_rate"],
                   r["parse_failure_rate"], f"{fmt(r['mean_input_tokens'])} / {fmt(r['mean_output_tokens'])}"]
                  for r in metrics.prompts(f)])]

    reg = registry.registry(db)
    rows = []
    for g in reg["generators"]:
        ft = g["details"].get("finetune") or {}
        extra = ""
        if ft:
            extra = (f"base {ft.get('base_model')}@{(ft.get('base_model_revision') or '')[:12]}, "
                     f"data {ft.get('dataset')}@{(ft.get('dataset_revision') or '')[:12]}, "
                     f"GGUF {fmt(ft.get('gguf_bytes'))} B, hub {ft.get('hub_repo') or 'n/a'}")
        rows.append([g["name"], g["provider"], g["model"], g["version"] or "n/a",
                     (g["digest"] or "")[:12] or "n/a", extra])
    rows += [[o["name"], o["provider"], o["model"], o["version"] or "n/a", "", o.get("note") or ""]
             for o in reg["others"]]
    md += ["## 7. Model registry", "",
           f"Ollama reachable at export time: {fmt(reg['ollama_reachable'])}.", "",
           table(["Name", "Provider", "Model", "Last reported version", "Digest", "Details"], rows),
           "Prompt versions: " + ", ".join(f"`{p['tag']}`" for p in reg["prompts"]), ""]

    md += eval_sections(queries.compare(db))
    return "\n".join(md).rstrip() + "\n"


def eval_sections(c: dict[str, Any]) -> list[str]:
    md = ["## 8. Evaluation (golden set)", ""]
    if not c["golden_set"]:
        md += ["_No golden-set evaluation has been run yet (`python -m eval.run`)._", ""]
    else:
        r = c["retrieval"]
        md += [f"Golden set **{c['golden_set']}**" + (f" on lecture *{r['lecture_title']}*" if r else "") + ".", ""]
        if r and r["metrics"]:
            rm = r["metrics"]["retrieval"]
            ks = [k for k in rm if k.startswith("hit@")]
            md += ["**M6 retrieval (shared retriever, answerable questions)**", "",
                   table(["n", *ks, "MRR", "Context precision", "Average precision"],
                         [[rm["n"], *[rm[k] for k in ks], rm["mrr"], rm["context_precision"],
                           rm["average_precision"]]]),
                   *threshold_lines(r["metrics"]["threshold"])]
        gens = c["generators"]
        if gens:
            def m(run, *path):
                v = run["metrics"] or {}
                for p in path:
                    v = (v or {}).get(p) if isinstance(v, dict) else None
                return v
            md += ["**Generators** (judge: " + ", ".join(sorted({(g["prompt_versions"] or {}).get("judge", "off")
                                                                 for g in gens})) + ")", "",
                   table(["Metric", *[g["generator"] for g in gens]], [
                       ["Model / version", *[g["model"] for g in gens]],
                       ["Status", *[g["status"] for g in gens]],
                       ["Questions", *[m(g, "n") for g in gens]],
                       ["M8 refusal accuracy (should refuse -> refused)", *[m(g, "refusal_accuracy") for g in gens]],
                       ["  refused by threshold", *[m(g, "refusal", "unanswerable", "by_threshold") for g in gens]],
                       ["  refused by model", *[m(g, "refusal", "unanswerable", "by_model") for g in gens]],
                       ["False refusals (answerable but refused)",
                        *[m(g, "refusal", "false_refusals", "refused") for g in gens]],
                       ["Decision accuracy (answer vs refuse)", *[m(g, "decision_accuracy") for g in gens]],
                       ["M7 faithfulness (mean)", *[m(g, "faithfulness") for g in gens]],
                       ["Hallucination rate", *[m(g, "hallucination_rate") for g in gens]],
                       ["Correctness (answered)", *[m(g, "correctness_answered") for g in gens]],
                       ["Correctness (all answerable)", *[m(g, "correctness_all_answerable") for g in gens]],
                       ["Latency p50 / p95 (ms)", *[f"{fmt(m(g, 'latency', 'p50_ms'))} / "
                                                     f"{fmt(m(g, 'latency', 'p95_ms'))}" for g in gens]],
                       ["Errors", *[str(m(g, "errors") or {}) for g in gens]],
                       ["Run finished", *[g["finished_at"] for g in gens]],
                   ])]
    if c["offline"]:
        md += ["## 9. SciQ results imported from Phase 10 (offline runs)", "",
               "Copied unchanged from `finetune/results/*.json` (see [finetuning.md](finetuning.md)).", ""]
        off = c["offline"]

        def o(run, *path):
            v = run["metrics"] or {}
            for p in path:
                v = (v or {}).get(p) if isinstance(v, dict) else None
            return v
        md += [table(["Set", "Model", "n", "Grounded-QA accuracy", "Token F1", "Refusal P / R", "MCQ JSON valid",
                      "Latency mean / p95 (ms)"],
                     [[r["golden_set"], r["generator"], r["n_items"], o(r, "gqa", "accuracy"), o(r, "gqa", "token_f1"),
                       f"{fmt(o(r, 'refusal', 'precision'))} / {fmt(o(r, 'refusal', 'recall'))}",
                       o(r, "mcq", "json_valid_rate"),
                       f"{fmt(o(r, 'latency_ms', 'mean'))} / {fmt(o(r, 'latency_ms', 'p95'))}"] for r in off])]
    return md


def threshold_lines(t: dict[str, Any]) -> list[str]:
    return [
        f"**RAG_MIN_SCORE check** (current value {t['threshold']}; top retrieval score per question)", "",
        table(["Kind", "n", "min", "median", "max", "below threshold", "at/above"],
              [[k, d["n"], d.get("min"), d.get("median"), d.get("max"), d["below_threshold"],
                d["at_or_above_threshold"]] for k, d in t["by_kind"].items()]),
        f"Answerable questions refused by the threshold alone: {t['answerable'].get('wrongly_refused_by_threshold')}. "
        f"Unanswerable: {t['unanswerable'].get('refused_by_threshold')} refused by the threshold, "
        f"{t['unanswerable'].get('passed_to_model')} passed to the model. Lowest answerable score "
        f"{fmt(t['answerable_min'])}, highest unanswerable {fmt(t['unanswerable_max'])} "
        f"(separable by a threshold alone: {fmt(t['separable'])}, gap {fmt(t['gap'])}).", "",
    ]


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--from", dest="date_from", type=date.fromisoformat)
    ap.add_argument("--to", dest="date_to", type=date.fromisoformat)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = ap.parse_args(argv)

    from app.core.config import get_settings
    from app.db.session import get_session_factory
    from app.services.llm.generators import get_generator_registry
    from app.services.llm.model_info import get_ollama_info
    from app.services.llm.pricing import get_pricing
    from app.services.llm.prompts import get_prompt_registry
    from app.services.llmops import LlmOpsMetrics, MetricFilter
    from app.services.model_registry import ModelRegistryService

    settings = get_settings()
    gens = get_generator_registry()
    registry = ModelRegistryService(settings, gens, get_prompt_registry(), get_ollama_info(settings.finetuned_base_url))
    f = MetricFilter(date_from=args.date_from, date_to=args.date_to)
    with get_session_factory()() as db:
        text = build(db, LlmOpsMetrics(db, get_pricing(), gens), registry, f, datetime.now(UTC))
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8")
    print(f"Wrote {args.out} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
